import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function register(page: Page, name = '科普编辑') {
  const email = `editor-${Date.now()}-${Math.random().toString(16).slice(2)}@e2e.local`
  await page.goto('/login')
  await page.getByRole('button', { name: '注册账号', exact: true }).click()
  await page.getByLabel('你的名字').fill(name)
  await page.getByLabel('邮箱地址').fill(email)
  await page.getByLabel('密码', { exact: true }).fill('E2eUserPassword123!')
  await page.getByRole('button', { name: '创建账号并进入' }).click()
  await expect(page.getByRole('heading', { name: '从一个主题，开始探索.' })).toBeVisible()
  return email
}

test('完整知识树流程：逐层生成、编辑采纳、恢复、导出、账号隔离', async ({
  page,
  browser,
}, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await register(page)
  await expect(page.locator('.topic-card')).toHaveCount(12)
  await page.screenshot({ path: testInfo.outputPath('topics-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: /医疗与健康.*开始构建知识树/ }).click()
  await page.getByRole('button', { name: '创建知识树', exact: true }).click()
  await expect(page.getByRole('heading', { name: '医疗与健康', exact: true })).toBeVisible()
  await page.waitForURL(/\/trees\/[a-z0-9-]+$/)
  const treeUrl = page.url()
  await page.getByRole('button', { name: 'AI 继续细分', exact: true }).click()
  await expect(page.getByRole('heading', { name: '本轮拆分建议' })).toBeVisible()
  // Suggestions are not in the formal tree before acceptance.
  await expect(page.getByRole('button', { name: '选择节点 基础认知', exact: true })).toHaveCount(0)
  await page.getByLabel('建议 1 名称').fill('疾病基础认知')
  await page.getByLabel('采纳建议 3').uncheck()
  await page.getByRole('button', { name: '采纳选中的 2 个节点' }).click()
  await page.getByRole('button', { name: '选择节点 疾病基础认知', exact: true }).click()
  await page.getByRole('button', { name: 'AI 继续细分', exact: true }).click()
  await page.getByRole('button', { name: '采纳选中的 2 个节点' }).click()
  await page.getByRole('button', { name: '选择节点 术语释义', exact: true }).click()
  await page.getByRole('button', { name: '确认此节点', exact: true }).click()
  await expect(page.getByRole('button', { name: '取消确认' })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('tree-desktop.png'), fullPage: true })
  await page.reload()
  await expect(page.getByRole('button', { name: '选择节点 术语释义', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '预览与导出' }).click()
  await expect(page.locator('.json-preview')).toContainText('schemaVersion')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载并保存版本' }).click()
  const download = await downloadEvent
  const output = testInfo.outputPath('tree-export.json')
  await download.saveAs(output)
  const data = JSON.parse(await readFile(output, 'utf8'))
  expect(data.schemaVersion).toBe('1.0')
  expect(data.root.children).toHaveLength(2)
  expect(data.root.children[0].children).toHaveLength(2)
  expect(data.root.children[0].children[0].children).toEqual([])
  expect(JSON.stringify(data)).not.toContain('status')
  await expect(page.getByRole('heading', { name: '导出历史' })).toBeVisible()
  await page.getByRole('button', { name: '关闭弹窗' }).click()
  const otherContext = await browser.newContext()
  const other = await otherContext.newPage()
  await register(other, '另一位编辑')
  await other.goto(treeUrl)
  await expect(other.getByText('内容不存在或无权访问')).toBeVisible()
  await otherContext.close()
  expect(errors).toEqual([])
})

