test('分支删除与整树复制', async ({ page }) => {
  await register(page)
  await page.getByRole('button', { name: /生命科学.*开始构建知识树/ }).click()
  await page.getByRole('button', { name: '创建知识树', exact: true }).click()
  await page.getByRole('button', { name: '手动添加子节点' }).click()
  await page.getByRole('dialog').getByLabel('节点名称').fill('细胞')
  await page.getByRole('button', { name: '添加节点', exact: true }).click()
  await page.getByRole('button', { name: '选择节点 细胞', exact: true }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: '删除此分支' }).click()
  await expect(page.getByRole('button', { name: '选择节点 细胞', exact: true })).toHaveCount(0)
  const original = page.url()
  await page.getByRole('button', { name: '复制知识树', exact: true }).click()
  await expect(page.getByRole('heading', { name: '生命科学 · 副本' })).toBeVisible()
  expect(page.url()).not.toBe(original)
})

